"""Stable identifiers for machine-readable audit findings."""

from enum import Enum


class FindingCode(str, Enum):
    IDENTITY_MISSING = "IDENTITY_MISSING"
    AUTHZ_MISSING = "AUTHZ_MISSING"
    ROLE_MISMATCH = "ROLE_MISMATCH"
    UNAUTHORIZED_ACTION = "UNAUTHORIZED_ACTION"
    COMMUNICATION_UNENCRYPTED = "COMMUNICATION_UNENCRYPTED"
    INTEGRITY_FAIL = "INTEGRITY_FAIL"
    AUTH_HEADER_MISSING = "AUTH_HEADER_MISSING"
    BEHAVIOR_ANOMALY = "BEHAVIOR_ANOMALY"
    DENIED_ACTION_BURST = "DENIED_ACTION_BURST"
    POLICY_VIOLATION = "POLICY_VIOLATION"
    DATA_EXPOSURE = "DATA_EXPOSURE"
    UNSAFE_EXPORT = "UNSAFE_EXPORT"
    SENSITIVE_DATA_IN_LOG = "SENSITIVE_DATA_IN_LOG"
    LOG_MISSING = "LOG_MISSING"
    TRACE_MISSING = "TRACE_MISSING"
    INCOMPLETE_AUDIT_RECORD = "INCOMPLETE_AUDIT_RECORD"
    GOVERNANCE_MISSING = "GOVERNANCE_MISSING"
    POLICY_CHANGE_NO_APPROVAL = "POLICY_CHANGE_NO_APPROVAL"
    OUTDATED_PATCH = "OUTDATED_PATCH"


ALL_FINDING_CODES = frozenset(code.value for code in FindingCode)
